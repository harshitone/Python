# String Basics

str1 = 'Hii' #use single quote
str2 = "Welcome to python programming" #use double qoute ->universal way to write string in double quote
str3 = '''My name is Harshit''' # use triple quote

# All string will print
print(str1) #Hii
print(str2) #Welcome to python programming
print(str3) #My name is Harshit

# String Concatenate

print("Hello" + " Harshit") # Hello Harshit
print("Hello" +" " + "Harshit") # Another Way

#String Length

print(len(str1))  #3
print(len(str2)) #29 Whitespace will also count in length
print(len(str3)) #18 Whitespace will also count in length